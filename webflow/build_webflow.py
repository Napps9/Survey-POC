def js(name, kind="function"):
    """One top-level declaration, by name, brace-matched."""
    pat = rf"\n  (?:// [^\n]*\n  )*{'function ' if kind == 'function' else 'const '}{name}\b"
    m = re.search(pat, script)
    assert m, "JS not found: " + name
    i = script.index(name, m.start())
    if kind == "const" and "{" not in script[i:script.index("\n", i)]:
        return script[m.start():script.index("\n", i)] + "\n"
    depth, j = 0, script.index("{", i)
    while True:
        if script[j] == "{":
            depth += 1
        elif script[j] == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    return script[m.start():j + 1] + "\n"


