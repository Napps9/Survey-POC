# The offline fallback deck. It exists so an emailed copy still shows something
# when the embed can't reach the network; a hosted page is already online, and
# if the player is unreachable the screenshot plus the full-screen link says the
# same thing for none of the weight.
DECK = re.compile(r"\.vd\b|\.vd-|@keyframes vd")


def drop_deck(text):
    """Strip .vd rules, including the ones nested inside @media blocks."""
    kept = []
    for sel, chunk in split_rules(text):
        if sel.startswith("@media") or sel.startswith("@supports"):
            head, inner = chunk[:chunk.index("{") + 1], chunk[chunk.index("{") + 1:chunk.rindex("}")]
            inner = drop_deck(inner)
            if inner.strip():
                kept.append(head + inner + "}")
            continue
        if DECK.search(sel):
            continue
        kept.append(chunk)
    return "".join(kept)


css = drop_deck(style)

# Rules for the chrome we just removed. Left in, they'd be dead weight in a
# handover kit and — worse — actively confusing: someone would style a
# .topbar in Webflow and wonder why two sets of rules fought over it.
DEAD = re.compile(r"\.topbar|nav\.sidenav|\.nav-link|\.nav-label|\.prepared-for|"
                  r"\.theme-toggle|\.logo\b|(?:^|[\s,>])footer\b")


def drop_chrome(text):
    """Drop dead selectors. Multi-selector rules keep the selectors still live —
    `.shell, main, nav.sidenav{ min-width: 0 }` must keep its first two."""
    kept = []
    for sel, chunk in split_rules(text):
        if sel.startswith("@media") or sel.startswith("@supports"):
            head, inner = chunk[:chunk.index("{") + 1], chunk[chunk.index("{") + 1:chunk.rindex("}")]
            inner = drop_chrome(inner)
            if inner.strip():
                kept.append(head + inner + "}")
            continue
        if not sel or sel.startswith("@") or sel.startswith(":root"):
            kept.append(chunk)
            continue
        live = [p for p in (p.strip() for p in sel.split(",")) if p and not DEAD.search(p)]
        if not live:
            continue
        if len(live) == len([p for p in sel.split(",") if p.strip()]):
            kept.append(chunk)
        else:
            cut = chunk.index("{")
            head, body = chunk[:cut], chunk[cut:]
            kept.append(head.replace(head.strip().split("*/")[-1].strip() or head.strip(),
                                     ", ".join(live)) + body)
    return "".join(kept)


css = drop_chrome(css)


def all_selectors(text):
    out = []
    for sel, chunk in split_rules(text):
        if sel.startswith("@media") or sel.startswith("@supports"):
            out += all_selectors(chunk[chunk.index("{") + 1:chunk.rindex("}")])
        elif sel:
            out += [p.strip() for p in sel.split(",")]
    return out


