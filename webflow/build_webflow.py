"""Strip the emailable one-pager down to a Webflow rebuild kit.

The shipped file is one 583KB document because it has to survive being emailed
and opened from a desktop: fonts, images and the offline fallback deck are all
base64'd into it. None of that earns its place on a hosted marketing page, so
this pulls the three apart:

    assets/            every payload as a real file, for Webflow's asset panel
    styles.css         the stylesheet, minus the fonts and the fallback deck
    index.html         a reference build of the PUBLIC page — same design, copy
                       rewritten off the named client
    embed-verto-demo.html   the one part Webflow can't draw: the device mockup
                       with the live Verto, sized for an HTML Embed element

Everything is extracted by anchor or by CSS selector, never by line number —
the source is regenerated by build_research.py and its line numbers move.
"""

