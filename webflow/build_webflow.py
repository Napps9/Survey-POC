# ------------------------------------------------------------------ CSS ----
style = flat[flat.index("<style>") + 7:flat.index("</style>")]


def split_rules(css):
    """Top-level rules, each as (selector, whole_text). @media keeps its block."""
    out, i, depth, start = [], 0, 0, 0
    while i < len(css):
        c = css[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                chunk = css[start:i + 1]
                # The selector is reported with comments stripped. A rule
                # preceded by a banner comment otherwise reports a "selector"
                # starting with /* — so `@media` blocks weren't recognised as
                # such, and were kept whole with their dead rules inside.
                sel = re.sub(r"/\*.*?\*/", "", chunk[:chunk.index("{")], flags=re.S).strip()
                out.append((sel, chunk))
                start = i + 1
        i += 1
    tail = css[start:].strip()
    if tail:
        out.append(("", css[start:]))
    return out


rules = split_rules(style)
